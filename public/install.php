  <div class="brand big"><span class="mark">MF</span><span>Motambarea Farmers<small>Buying management · setup</small></span></div>
<?php if ($installed && !$done): ?>
  <div class="card"><h1>Already installed</h1><p>The system is set up. <a href="index.php">Go to sign in</a>.</p></div>
<?php elseif ($done): ?>
  <div class="card"><h1>Installation complete</h1><p>Sign in with the administrator account you just created, then set your buying prices.</p><p><a class="btn btn-primary" href="index.php">Go to sign in</a></p></div>
<?php else: ?>
  <form method="post" class="card form">
    <?= csrf_field() ?>
    <h1>Set up the system</h1>
    <?php if ($error): ?><div class="flash flash-error"><?= e($error) ?></div><?php endif; ?>
    <fieldset>
      <legend>Database</legend>
      <p class="hint">On Hostinger: hPanel → Databases → MySQL Databases. Create a database and user, then enter them here. The host is usually <code>localhost</code>.</p>
      <label>Type<select name="driver" data-driver>
        <option value="mysql"<?= $v['driver'] !== 'sqlite' ? ' selected' : '' ?>>MySQL / MariaDB (Hostinger)</option>
        <option value="sqlite"<?= $v['driver'] === 'sqlite' ? ' selected' : '' ?>>SQLite file (testing on a computer only)</option>
      </select></label>
      <div class="row" data-mysql>
        <label class="grow">Host<input name="host" value="<?= e($v['host']) ?>"></label>
        <label>Port<input name="port" value="<?= e($v['port']) ?>" inputmode="numeric"></label>
      </div>
      <div class="row" data-mysql>
        <label>Database name<input name="name" value="<?= e($v['name']) ?>" placeholder="u123456789_pos"></label>
        <label>Database user<input name="user" value="<?= e($v['user']) ?>" placeholder="u123456789_pos" autocomplete="off"></label>
        <label>Database password<input type="password" name="pass" autocomplete="new-password"></label>
      </div>
    </fieldset>
    <fieldset>
      <legend>Company</legend>
      <div class="row">
        <label class="grow">Company name<input name="company_name" value="<?= e($v['company_name']) ?>" required></label>
        <label>Location<input name="company_location" value="<?= e($v['company_location']) ?>"></label>
        <label>Phone<input name="company_phone" value="<?= e($v['company_phone']) ?>" placeholder="+237 …"></label>
      </div>
    </fieldset>
    <fieldset>
      <legend>First administrator</legend>
      <div class="row">
        <label class="grow">Full name<input name="admin_name" value="<?= e($v['admin_name']) ?>" required></label>
        <label>Username<input name="admin_user" value="<?= e($v['admin_user']) ?>" required autocapitalize="none"></label>
        <label>Password (8+ characters)<input type="password" name="admin_pass" minlength="8" required autocomplete="new-password"></label>
      </div>
    </fieldset>
    <button class="btn btn-primary btn-lg" type="submit">Install</button>
  </form>
<?php endif; ?>
