<?php
declare(strict_types=1);

/*
 * One-time installer. Creates the database tables, the first administrator and config/config.php.
 * After a successful install it refuses to run again (delete config/config.php to reinstall on an empty database).
 */
require __DIR__ . '/../app/bootstrap.php';

app_boot(false);
start_session();
send_security_headers();

$installed = is_file(CONFIG_FILE);
$error = null;
$done = false;
$v = [
    'driver' => 'mysql', 'host' => 'localhost', 'port' => '3306', 'name' => '', 'user' => '',
    'company_name' => 'Motambarea Farmers', 'company_location' => 'Kumba, Cameroon', 'company_phone' => '',
    'admin_name' => '', 'admin_user' => 'admin',
];

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    foreach ($v as $k => $_) {
        $v[$k] = in_str($_POST, $k, 120);
    }
    $pass = (string) ($_POST['pass'] ?? '');
    $adminPass = (string) ($_POST['admin_pass'] ?? '');
    $dbc = [
        'driver' => $v['driver'] === 'sqlite' ? 'sqlite' : 'mysql',
        'host' => $v['host'], 'port' => (int) $v['port'], 'name' => $v['name'], 'user' => $v['user'], 'pass' => $pass,
        'sqlite_path' => ROOT . '/storage/pos.sqlite',
    ];
    $adminUser = mb_strtolower($v['admin_user']);

    if (!csrf_valid()) {
        $error = 'Session expired. Reload the page and try again.';
    } elseif (mb_strlen($v['admin_name']) < 2 || !preg_match('/^[a-z0-9._-]{3,50}$/', $adminUser)) {
        $error = 'Enter the administrator’s name and a username (3–50 letters/numbers).';
    } elseif ($p = password_problem($adminPass)) {
        $error = $p;
    } elseif (!is_writable(dirname(CONFIG_FILE))) {
        $error = 'The folder ' . dirname(CONFIG_FILE) . ' is not writable. In Hostinger File Manager set its permissions to 755.';
    } else {
        try {
            $pdo = db_connect($dbc);
            $exists = $dbc['driver'] === 'mysql'
                ? $pdo->query("SHOW TABLES LIKE 'purchases'")->fetchColumn()
                : $pdo->query("SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'purchases'")->fetchColumn();
            if ($exists) {
                throw new RuntimeException('This database already contains POS tables. Use an empty database.');
            }
            install_database($pdo, ['username' => $adminUser, 'full_name' => $v['admin_name'], 'password' => $adminPass], [
                'name' => $v['company_name'], 'location' => $v['company_location'], 'phone' => $v['company_phone'],
            ]);
            $config = [
                'app_name' => 'Motambarea Farmers POS',
                'timezone' => 'Africa/Douala',
                'debug' => false,
                'db' => $dbc,
                'public_price_origins' => ['https://motambeareafarmers.com', 'https://www.motambeareafarmers.com'],
            ];
            $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn " . var_export($config, true) . ";\n";
            if (file_put_contents(CONFIG_FILE, $php, LOCK_EX) === false) {
                throw new RuntimeException('Could not write ' . CONFIG_FILE);
            }
            @chmod(CONFIG_FILE, 0640);
            $done = true;
        } catch (PDOException $ex) {
            $error = 'Could not connect to or set up the database: ' . $ex->getMessage();
        } catch (RuntimeException $ex) {
            $error = $ex->getMessage();
        }
    }
}
